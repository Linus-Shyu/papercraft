#!/usr/bin/env python3
"""Install Papercraft for every major agent / IDE.

Native skill directories (Agent Skills format, `SKILL.md`):
  DSH, shared ~/.agents, Claude Code, Cursor, Codex.

Pointer files for tools without a native skill directory (project-level):
  AGENTS.md, CLAUDE.md, GEMINI.md, .cursor/rules, .clinerules,
  .windsurf/rules, .continue/rules, .github/copilot-instructions.md,
  CONVENTIONS.md, .rules.

Usage:
  ./install.py --dsh                     # only ~/.dsh/skills/papercraft (old default)
  ./install.py --all                     # all native global dirs
  ./install.py --project DIR             # project native dirs + pointer files
  ./install.py --all --project DIR       # both
  ./install.py --pointers DIR            # pointer files only
  ./install.py --list                    # show the matrix
  ./install.py --uninstall [--project DIR] [--all]

  --copy        copy instead of symlink
  --force       replace an existing different install
  --dry-run     print actions, write nothing

Exit codes: 0 ok, 1 conflict, 2 usage/IO.
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent
MARK_BEGIN = "<!-- papercraft:begin -->"
MARK_END = "<!-- papercraft:end -->"
HEADER = "<!-- generated by papercraft; remove with: install.py --uninstall -->"

NATIVE_GLOBAL = [
    ("dsh", "DSH", Path.home() / ".dsh/skills/papercraft"),
    ("agents", "shared ~/.agents", Path.home() / ".agents/skills/papercraft"),
    ("claude", "Claude Code", Path.home() / ".claude/skills/papercraft"),
    ("cursor", "Cursor", Path.home() / ".cursor/skills/papercraft"),
    ("codex", "Codex", Path.home() / ".codex/skills/papercraft"),
]

NATIVE_PROJECT = [
    ("dsh", "DSH", ".dsh/skills/papercraft"),
    ("agents", "shared .agents", ".agents/skills/papercraft"),
    ("claude", "Claude Code", ".claude/skills/papercraft"),
    ("cursor", "Cursor", ".cursor/skills/papercraft"),
    ("codex", "Codex", ".codex/skills/papercraft"),
]

# id, display, relative path, mode (append|write), template
POINTERS = [
    ("agents", "AGENTS.md (universal)", "AGENTS.md", "append", "agents"),
    ("claude", "Claude Code memory", "CLAUDE.md", "append", "claude"),
    ("gemini", "Gemini CLI", "GEMINI.md", "append", "gemini"),
    ("cursor", "Cursor rule", ".cursor/rules/papercraft.mdc", "write", "cursor"),
    ("cline", "Cline", ".clinerules/papercraft.md", "write", "cline"),
    ("windsurf", "Windsurf", ".windsurf/rules/papercraft.md", "write", "windsurf"),
    ("continue", "Continue", ".continue/rules/papercraft.md", "write", "continue"),
    ("copilot", "GitHub Copilot", ".github/copilot-instructions.md", "append", "copilot"),
    ("aider", "Aider", "CONVENTIONS.md", "append", "aider"),
    ("zed", "Zed", ".rules", "append", "zed"),
]


def pointer_body(kind: str) -> str:
    skill = SRC / "SKILL.md"
    writing = SRC / "WRITING.md"
    reviewing = SRC / "REVIEWING.md"
    core = f"""## Papercraft — evidence-first paper writing & review

For any paper writing, auditing, reviewing, rebuttal, or submission task, read
`{skill}` and follow it.

Non-negotiables: no number without a source; no citation without verification;
no claim without evidence; no float without a reference; verify conference rules
against the current CFP; fail closed.

Standalone playbooks: `{writing}` (writing) and `{reviewing}` (reviewing).
"""
    if kind == "cursor":
        return (
            "---\n"
            "description: Papercraft evidence-first paper writing and review\n"
            'globs: ["**/*.tex", "**/*.bib", "**/*.md"]\n'
            "alwaysApply: true\n"
            "---\n"
            f"{HEADER}\n\n{core}"
        )
    return f"{HEADER}\n\n{core}"


def block(kind: str) -> str:
    return f"{MARK_BEGIN}\n{pointer_body(kind)}{MARK_END}\n"


def backup(path: Path) -> None:
    if not path.exists():
        return
    bak = path.with_name(path.name + ".papercraft.bak")
    if not bak.exists():
        shutil.copy2(path, bak)


def upsert_block(path: Path, text_block: str, dry: bool) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    pat = re.compile(re.escape(MARK_BEGIN) + r".*?" + re.escape(MARK_END) + r"\n?", re.S)
    if pat.search(old):
        new = pat.sub(text_block, old)
        action = "updated"
    else:
        new = (old.rstrip() + "\n\n" if old.strip() else "") + text_block
        action = "appended"
    if not dry:
        # Back up only when appending to a file that already has user content.
        if MARK_BEGIN not in old and old.strip():
            backup(path)
        path.write_text(new, encoding="utf-8")
    return action


def remove_block(path: Path, dry: bool) -> str:
    if not path.exists():
        return "missing"
    old = path.read_text(encoding="utf-8")
    pat = re.compile(r"\n?" + re.escape(MARK_BEGIN) + r".*?" + re.escape(MARK_END) + r"\n?", re.S)
    if not pat.search(old):
        return "no-block"
    new = pat.sub("\n", old).strip()
    if not dry:
        if new:
            path.write_text(new + "\n", encoding="utf-8")
        else:
            path.unlink()
    return "removed"


def write_dedicated(path: Path, text: str, dry: bool) -> str:
    if path.exists():
        old = path.read_text(encoding="utf-8")
        if old == text:
            return "ok"
        if HEADER not in old:
            return "exists (not ours; use --force)"
    if not dry:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return "written"


def install_native(target: Path, copy: bool, force: bool, dry: bool) -> str:
    if target.is_symlink():
        if target.resolve() == SRC.resolve():
            return "ok"
        if not force:
            return "exists (different link; use --force)"
        if not dry:
            target.unlink()
    elif target.exists():
        if not force:
            return "exists (use --force)"
        if not dry:
            shutil.rmtree(target)
    if not dry:
        target.parent.mkdir(parents=True, exist_ok=True)
        if copy:
            shutil.copytree(
                SRC, target,
                ignore=shutil.ignore_patterns(".git", "__pycache__", "*.pyc", ".DS_Store"),
            )
            (target / ".papercraft-source").write_text(str(SRC) + "\n", encoding="utf-8")
        else:
            os.symlink(SRC, target)
    return "copied" if copy else "linked"


def uninstall_native(target: Path, dry: bool) -> str:
    if target.is_symlink():
        if target.resolve() == SRC.resolve():
            if not dry:
                target.unlink()
            return "removed"
        return "skip (not ours)"
    if target.is_dir():
        marker = target / ".papercraft-source"
        if marker.exists() and marker.read_text(encoding="utf-8").strip() == str(SRC):
            if not dry:
                shutil.rmtree(target)
            return "removed"
        return "skip (no source marker)"
    if target.exists():
        return "skip (not a dir/link)"
    return "missing"


def main() -> int:
    ap = argparse.ArgumentParser(description="Install Papercraft for agents/IDEs")
    ap.add_argument("--dsh", action="store_true", help="only ~/.dsh/skills/papercraft")
    ap.add_argument("--all", action="store_true", help="all native global dirs")
    ap.add_argument("--target", metavar="DIR", help="single custom native target")
    ap.add_argument("--project", metavar="DIR", help="project root for native + pointers")
    ap.add_argument("--pointers", metavar="DIR", help="project root for pointer files only")
    ap.add_argument("--copy", action="store_true")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--uninstall", action="store_true")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args()

    if args.list:
        print("Native skill dirs (Agent Skills / SKILL.md):")
        for key, name, path in NATIVE_GLOBAL:
            print(f"  {key:8} {name:20} {path}")
        print("\nProject pointer files (run with --project DIR):")
        for key, name, rel, mode, _ in POINTERS:
            print(f"  {key:8} {name:28} {rel} ({mode})")
        print("\nExamples:\n  ./install.py --all\n  ./install.py --project /path/to/paper\n  ./install.py --all --project /path/to/paper")
        return 0

    if not (args.dsh or args.all or args.target or args.project or args.pointers or args.uninstall):
        args.dsh = True

    failures = 0
    mode = "copy" if args.copy else "symlink"
    print(f"source: {SRC}")
    print(f"mode:   {mode}{' (dry-run)' if args.dry_run else ''}")

    def do_native(entries, base: Path | None):
        nonlocal failures
        for key, name, path in entries:
            target = (base / path) if base else path
            if args.uninstall:
                res = uninstall_native(target, args.dry_run)
            else:
                res = install_native(target, args.copy, args.force, args.dry_run)
            if res.startswith("exists"):
                failures += 1
            print(f"  [{key:8}] {name:20} {target}  ->  {res}")

    if args.target:
        print("\nNative (custom):")
        do_native([("custom", "custom", Path(args.target).expanduser().resolve())], None)

    if args.all:
        print("\nNative (global):")
        do_native(NATIVE_GLOBAL, None)

    if args.dsh and not args.all:
        print("\nNative (DSH only):")
        do_native([NATIVE_GLOBAL[0]], None)

    project = Path(args.project).expanduser().resolve() if args.project else None
    if project:
        if args.uninstall:
            print("\nNative (project):")
            do_native(NATIVE_PROJECT, project)
        else:
            print("\nNative (project):")
            do_native(NATIVE_PROJECT, project)

    pointer_root = project or (Path(args.pointers).expanduser().resolve() if args.pointers else None)
    if pointer_root:
        print(f"\nPointers ({pointer_root}):")
        for key, name, rel, pmode, kind in POINTERS:
            path = pointer_root / rel
            if args.uninstall:
                if pmode == "append":
                    res = remove_block(path, args.dry_run)
                else:
                    if path.exists() and HEADER in path.read_text(encoding="utf-8"):
                        if not args.dry_run:
                            path.unlink()
                        res = "removed"
                    else:
                        res = "skip (not ours)" if path.exists() else "missing"
            else:
                if pmode == "append":
                    res = upsert_block(path, block(kind), args.dry_run)
                else:
                    res = write_dedicated(path, pointer_body(kind), args.dry_run)
            print(f"  [{key:8}] {name:28} {path}  ->  {res}")

    print("\nRESULT:", "PASS" if failures == 0 else f"{failures} conflict(s)")
    return 0 if failures == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
